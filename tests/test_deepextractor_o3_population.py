# The ``population`` config entry
# ---------------------------------------------------------------------------------------


def test_a_population_entry_expands_to_its_class_models(population: GlitchPopulation) -> None:
    """In place, beside ordinary entries, with the digest pinned."""
    plain = {"kind": "blip", "rate": 0.1, "amplitude_distribution": {"mean": 1.0, "std": 0.0}}
    models = normalize_glitch_models(
        [plain, {"population": preset.POPULATION_NAME, "digest": REGISTERED_DIGEST}, plain]
    )
    assert len(models) == 2 + len(population.classes)
    assert [m.serialize() for m in models[1:-1]] == [c.model.serialize() for c in population.classes]
    assert type(models[0]) is type(models[-1]) is not DeepExtractorGlitch


def test_a_population_entry_passes_its_settings_to_the_builder() -> None:
    """The digest a configuration pins is that of the population built with its settings."""
    settings = {"psd_file": "ET_15_full_cryo_psd", "detectors": ["E1", "E2"], "low_frequency_cutoff": 3.0}
    expected = get_glitch_population(preset.POPULATION_NAME, **settings)
    models = normalize_glitch_models([{"population": preset.POPULATION_NAME, "digest": expected.digest(), **settings}])
    assert [m.serialize() for m in models] == [c.model.serialize() for c in expected.classes]


def test_a_population_entry_without_a_digest_is_accepted() -> None:
    """The pin is optional."""
    assert len(normalize_glitch_models([{"population": preset.POPULATION_NAME}])) == len(DEEPEXTRACTOR_CLASSES)


def test_a_population_entry_refuses_a_digest_it_does_not_have() -> None:
    """A configuration pinned to the defaults refuses a run that changed a setting, and says both digests."""
    with pytest.raises(ValueError, match=r"has digest sha256:[0-9a-f]{64}, not the pinned " + REGISTERED_DIGEST):
        normalize_glitch_models(
            [{"population": preset.POPULATION_NAME, "digest": REGISTERED_DIGEST, "low_frequency_cutoff": 2.0}]
        )


@pytest.mark.parametrize(
    ("entry", "message"),
    [
        ({"population": "deepextractor-o3-v2"}, r"registered populations are \['deepextractor-o3-v1'"),
        ({"population": preset.POPULATION_NAME, "rate": 1.0}, r"does not take the arguments \['rate'\]"),
    ],
)
def test_a_population_entry_refuses_an_unknown_name_or_argument(entry: dict, message: str) -> None:
    """Both as ``ValueError``, the error every other bad glitch entry raises."""
    with pytest.raises(ValueError, match=message):
        normalize_glitch_models([entry])
