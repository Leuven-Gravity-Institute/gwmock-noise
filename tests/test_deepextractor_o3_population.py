def test_the_bundled_summary_is_the_harness_output_for_this_population(summary: dict) -> None:
    """Every label at any confidence, above the Omicron threshold, rate = count over livetime."""
    measurement = MEASUREMENTS[preset.POPULATION_NAME]
    assert measurement.summary_path == DEEPEXTRACTOR_SUMMARY_PATH
    assert measurement.confidence_minimum is None
    assert summary["selection"] == {"snr_minimum": SNR_MINIMUM, "confidence_minimum": None}
    assert tuple(summary["classes"]) == DEEPEXTRACTOR_CLASSES == tuple(preset.CLASS_PARAMETERS)
    livetime = summary["livetime_seconds"]
    assert livetime["pooled"] == pytest.approx(livetime["H1"] + livetime["L1"], rel=0.0, abs=0.0)
    for block in summary["classes"].values():
        assert block["counts"]["pooled"] == block["counts"]["H1"] + block["counts"]["L1"]
        for key in ("H1", "L1", "pooled"):
            assert block["rate_hz"][key] == pytest.approx(block["counts"][key] / livetime[key], rel=1e-12)


def test_the_bundled_summary_is_written_the_way_the_formatter_wants_it() -> None:
    """A re-measurement leaves the formatter nothing to do, and the file is not hand-edited."""
    on_disk = DEEPEXTRACTOR_SUMMARY_PATH.read_text(encoding="utf-8")
    assert render_summary(json.loads(on_disk)) == on_disk


@pytest.mark.parametrize("name", DEEPEXTRACTOR_CLASSES)
def test_registered_constants_are_the_measured_ones(summary: dict, name: str) -> None:
    """Rate rounded to five significant figures, exponent to four decimals, truncation up to 0.01."""
    rate, alpha, maximum = preset.CLASS_PARAMETERS[name]
    block = summary["classes"][name]
    assert rate == float(f"{block['rate_hz']['pooled']:.5g}")
    assert alpha == round(block["snr"]["truncated_pareto_alpha"], 4)
    assert maximum == math.ceil(block["snr"]["maximum"] * 100.0) / 100.0


@pytest.mark.parametrize("name", DEEPEXTRACTOR_CLASSES)
def test_the_registered_law_reproduces_the_measured_tail_index(summary: dict, name: str) -> None:
    """Draws from the truncated law have the Hill index the O3 sample has."""
    _, alpha, maximum = preset.CLASS_PARAMETERS[name]
    block = summary["classes"][name]["snr"]
    reproduced = expected_hill_of_truncated_draws(preset.REFERENCE_SNR_THRESHOLD, alpha, maximum)
    assert reproduced == pytest.approx(block["hill_alpha"], rel=1e-3)


def test_the_registered_classes_are_the_registered_constants(population: GlitchPopulation) -> None:
    """Each class is one DeepExtractor model restricted to its own label, at its own rate and tail."""
    assert [c.name for c in population.classes] == list(DEEPEXTRACTOR_CLASSES)
    for glitch_class in population.classes:
        rate, alpha, maximum = preset.CLASS_PARAMETERS[glitch_class.name]
        model = glitch_class.model
        assert isinstance(model, DeepExtractorGlitch)
        assert model.glitch_classes == [glitch_class.name]
        assert model.rate == rate
        assert model.serialize()["snr"] == {
            "distribution": "power_law",
            "minimum": SNR_MINIMUM,
            "alpha": alpha,
            "maximum": maximum,
        }
        assert model.revision == preset.DATASET_REVISION
        assert model.low_frequency_cutoff == preset.DEFAULT_LOW_FREQUENCY_CUTOFF
        assert model.psd_file == preset.DEFAULT_PSD
        assert model.detectors is None


