def test_the_population_round_trips_through_its_serialization(population: GlitchPopulation) -> None:
    """A manifest can carry the definition and rebuild exactly it."""
    rebuilt = GlitchPopulation.deserialize(json.loads(json.dumps(population.serialize())))
    assert rebuilt.serialize() == population.serialize()
    assert rebuilt.digest() == population.digest()


def test_the_registered_digest_is_the_one_campaigns_pin(population: GlitchPopulation) -> None:
    """Pinned deliberately; the builder with no arguments is the registered population."""
    assert population.digest() == REGISTERED_DIGEST
    assert deepextractor_o3_population().digest() == REGISTERED_DIGEST


@pytest.mark.parametrize(
    "arguments",
    [
        {"psd_file": "ET_15_full_cryo_psd"},
        {"detectors": ["E1"]},
        {"low_frequency_cutoff": 2.0},
        {"revision": "main"},
    ],
)
def test_a_run_setting_reaches_every_class_and_moves_the_digest(arguments: dict) -> None:
    """The registry passes builder arguments through; the result is a different, pinnable population."""
    population = get_glitch_population(preset.POPULATION_NAME, **arguments)
    assert population.digest() != REGISTERED_DIGEST
    ((key, value),) = arguments.items()
    for glitch_class in population.classes:
        assert glitch_class.model.serialize()[key] == value


def test_the_registry_lists_both_populations() -> None:
    """The new population sits beside the existing one."""
    assert available_glitch_populations() == ["deepextractor-o3-v1", "et-o3-anchored-v1"]


