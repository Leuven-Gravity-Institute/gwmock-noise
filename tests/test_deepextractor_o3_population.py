"""Tests for the ``deepextractor-o3-v1`` glitch population and the ``population`` config entry.

The registered rates, tails and truncations are measurements summarized in
``src/gwmock_noise/data/glitch_population/deepextractor_o3_summary.json`` and regenerated by
``scripts/measure_glitch_population_anchors.py --population deepextractor-o3-v1``. They are
asserted against that summary, so a constant edited by hand or a summary regenerated under a
different selection fails here.

A configuration names the population, and may pin its digest; the entry expands to the
population's class models. That expansion is tested without the waveform dataset: building a
model does not download it.
"""

from __future__ import annotations

import json
import math
import re
from pathlib import Path

import numpy as np
import pytest
from measure_glitch_population_anchors import (
    DEEPEXTRACTOR_CLASSES,
    DEEPEXTRACTOR_SUMMARY_PATH,
    MEASUREMENTS,
    NON_GLITCH_LABELS,
    SNR_MINIMUM,
    Triggers,
    expected_hill_of_truncated_draws,
    render_summary,
    summarize,
)

from gwmock_noise.data.glitch_population import load_deepextractor_o3_summary
from gwmock_noise.glitches import normalize_glitch_models
from gwmock_noise.glitches.deepextractor import DeepExtractorGlitch
from gwmock_noise.populations import (
    GlitchPopulation,
    available_glitch_populations,
    deepextractor_o3_population,
    get_glitch_population,
)
from gwmock_noise.populations import deepextractor_o3 as preset
from gwmock_noise.populations.registry import UnknownPopulationArgumentError

#: The population's record page, whose tables are asserted against the summary.
RECORD_PAGE = Path(__file__).resolve().parents[1] / "docs" / "dev" / "deepextractor_o3_population.md"

#: The registered population's digest, as a campaign pins it. Moving it is the act of saying
#: that what the registered population injects has changed.
REGISTERED_DIGEST = "sha256:bd91a26c59c817bb9310e1c223fd7d2562dd8b5bf7885e9b2a6040b74b28918c"


@pytest.fixture(name="summary")
def _summary() -> dict:
    """The bundled measurement the registered constants are asserted against."""
    return load_deepextractor_o3_summary()


@pytest.fixture(name="population")
def _population() -> GlitchPopulation:
    """The registered population, as a campaign resolves it."""
    return get_glitch_population(preset.POPULATION_NAME)


