def test_a_population_that_does_not_cover_an_interferometer_is_refused() -> None:
    """Both when counting and when realizing, because both would be silently wrong."""
    scoped = et_o3_anchored_population()
    scoped = replace(
        scoped,
        classes=tuple(replace(entry, model=replace_detectors(entry.model, ["E1"])) for entry in scoped.classes),
    )
    with pytest.raises(ValueError, match="no glitch model applies to E2"):
        scoped.expected_counts(livetime_seconds=1.0, detectors=["E1", "E2"])
    with pytest.raises(ValueError, match="no glitch model applies to E2"):
        scoped.realize(detectors=["E1", "E2"], duration=1.0, sampling_frequency=SAMPLING_FREQUENCY, seed=1)


def replace_detectors(model: BlipGlitch, detectors: list[str]) -> BlipGlitch:
    """Rebuild one model scoped to ``detectors``.

    The models are slotted dataclasses with init-only ``kind`` fields, so a scoped copy is
    made by round-tripping the serialization rather than by ``dataclasses.replace``.
    """
    from gwmock_noise.glitches.models import normalize_glitch_models

    (rebuilt,) = normalize_glitch_models([model.serialize() | {"detectors": detectors}])
    return rebuilt


