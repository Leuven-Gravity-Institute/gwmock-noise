#: The registered population's digest. A campaign pins this, so it is pinned here too: a
#: change to any registered quantity moves it, and moving it is a deliberate act that
#: belongs in the same commit as the change and in the anchor page's record.
REGISTERED_DIGEST = "sha256:58fb23aef4b4dd0d0038ebdae09da51bdaf638821aca0df97ead74dcbc1dc3b0"

#: Sampling frequency the registered population needs. Its short class is supported up to
#: 780 Hz, so anything below 1560 Hz cannot represent it and is refused rather than
#: narrowed.
SAMPLING_FREQUENCY = 2048.0


@pytest.fixture(name="summary")
def _summary() -> dict:
    """The bundled measurement the registered constants are asserted against."""
    return load_o3_reference_summary()


@pytest.fixture(name="population")
def _population() -> GlitchPopulation:
    """The registered population, as a campaign would resolve it."""
    return get_glitch_population(anchors.POPULATION_NAME)


def _busy_population(**overrides: float) -> GlitchPopulation:
    """The registered population with both rates raised, so short tests see events.

    Rates are the one registered quantity a test may move without changing what is being
    tested: everything else -- the morphologies, the amplitude laws, the coherence -- is
    the registered one. Raising them is what lets a few seconds of generated data stand in
    for the hours a campaign runs.
    """
    return et_o3_anchored_population(short_rate_hz=0.5, coherent_rate_hz=0.5, **overrides)


