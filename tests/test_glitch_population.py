def test_the_population_round_trips_through_its_serialization(population: GlitchPopulation) -> None:
    """A manifest can carry the definition and rebuild exactly it."""
    payload = json.loads(json.dumps(population.serialize()))
    rebuilt = GlitchPopulation.deserialize(payload)

    assert rebuilt.serialize() == population.serialize()
    assert rebuilt.digest() == population.digest()
    assert rebuilt.classes[1].model.network == NetworkCoherence(
        participation_probability=anchors.COHERENT_PARTICIPATION_PROBABILITY,
        amplitude_ratio_std=anchors.COHERENT_AMPLITUDE_RATIO_STD,
    )


def test_the_registered_digest_is_the_one_campaigns_pin(population: GlitchPopulation) -> None:
    """Pinned deliberately.

    Updating this literal is the act of saying that what the registered population injects
    has changed. If this fails and the change was intended, the anchor page's record of the
    digest has to move with it.
    """
    assert population.digest() == REGISTERED_DIGEST
    assert get_glitch_population(anchors.POPULATION_NAME).digest() == REGISTERED_DIGEST


def test_the_digest_travels_because_the_psd_is_named_not_pathed(population: GlitchPopulation) -> None:
    """An absolute path in the serialization would make the digest machine-dependent."""
    payload = population.serialize()
    for entry in payload["classes"]:
        psd_file = entry["model"]["psd_file"]
        assert psd_file == anchors.DEFAULT_PSD
        assert not psd_file.startswith("/")


