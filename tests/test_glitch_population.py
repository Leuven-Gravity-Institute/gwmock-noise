def test_a_population_at_zero_rate_injects_nothing_and_says_so() -> None:
    """An empty population is a legitimate configuration, not an error.

    It is the control arm of any glitch study, so it has to produce exactly zero strain
    rather than "almost none", and its stamp has to record that it produced nothing rather
    than leaving a consumer to infer it from an absent file.
    """
    empty = et_o3_anchored_population(short_rate_hz=0.0, coherent_rate_hz=0.0)
    realization = empty.realize(detectors=["E1", "E2"], duration=64.0, sampling_frequency=SAMPLING_FREQUENCY, seed=3)

    assert realization.events == []
    assert realization.stamp["event_count"] == 0
    for strain in realization.strain.values():
        assert not np.any(strain)
    rows = empty.expected_counts(livetime_seconds=1e6, detectors=["E1", "E2"])
    assert all(row.expected == 0.0 for row in rows)
    assert empty.digest() != REGISTERED_DIGEST


def test_a_coherent_class_at_zero_participation_still_draws_its_network_events() -> None:
    """Zero participation empties the channels without emptying the process.

    The distinction matters for the decomposition: a campaign sweeping participation is
    varying how much of a fixed population reaches the instruments, not how large the
    population is.
    """
    silent = et_o3_anchored_population(short_rate_hz=0.0, coherent_rate_hz=0.5, participation_probability=0.0)
    realization = silent.realize(detectors=["E1", "E2"], duration=64.0, sampling_frequency=SAMPLING_FREQUENCY, seed=4)
    assert realization.events == []

    coherent = [
        row
        for row in silent.expected_counts(livetime_seconds=64.0, detectors=["E1", "E2"])
        if row.glitch_class == "network_coherent"
    ]
    assert len(coherent) == 2
    for row in coherent:
        assert row.expected == 0.0
        assert row.network_events == pytest.approx(0.5 * 64.0)


@pytest.mark.parametrize(
    ("threshold", "expected"),
    [(7.5, 1.0), (7.4, 1.0), (344.38, 0.0), (400.0, 0.0)],
)
def test_the_amplitude_law_survives_its_own_boundaries(threshold: float, expected: float) -> None:
    """At and below the threshold everything survives; at and above the truncation nothing does."""
    law = PowerLawSNRDistribution(
        minimum=anchors.REFERENCE_SNR_THRESHOLD,
        alpha=anchors.SHORT_SNR_ALPHA,
        maximum=anchors.SHORT_SNR_MAXIMUM,
    )
    assert law.survival(threshold) == pytest.approx(expected)


def test_the_truncated_survival_matches_what_the_sampler_draws() -> None:
    """Closed form against the generator, so the selection factor is not a separate model."""
    law = PowerLawSNRDistribution(
        minimum=anchors.REFERENCE_SNR_THRESHOLD,
        alpha=anchors.SHORT_SNR_ALPHA,
        maximum=anchors.SHORT_SNR_MAXIMUM,
    )
    rng = np.random.default_rng(404)
    draws = np.array([law.sample(rng) for _ in range(50_000)])
    assert draws.min() >= anchors.REFERENCE_SNR_THRESHOLD
    assert draws.max() <= anchors.SHORT_SNR_MAXIMUM
    for threshold in (10.0, 20.0, 50.0, 100.0):
        empirical = float(np.mean(draws >= threshold))
        assert empirical == pytest.approx(law.survival(threshold), abs=4.0 * np.sqrt(empirical / draws.size))


def test_an_untruncated_tail_survives_past_any_truncation_point() -> None:
    """The truncation is doing work, not decorating the configuration."""
    threshold, alpha = anchors.REFERENCE_SNR_THRESHOLD, anchors.SHORT_SNR_ALPHA
    untruncated = PowerLawSNRDistribution(minimum=threshold, alpha=alpha)
    truncated = PowerLawSNRDistribution(minimum=threshold, alpha=alpha, maximum=anchors.SHORT_SNR_MAXIMUM)
    assert untruncated.survival(anchors.SHORT_SNR_MAXIMUM) > 0.0
    assert truncated.survival(anchors.SHORT_SNR_MAXIMUM) == 0.0
    assert truncated.survival(50.0) < untruncated.survival(50.0)


def test_the_population_refuses_a_rate_too_low_to_represent_its_band(
    population: GlitchPopulation,
) -> None:
    """A band the Nyquist frequency cannot carry is refused rather than quietly narrowed.

    The registered short class is supported to 780 Hz, so it needs at least 1560 Hz. A run
    that narrowed it instead would inject a class that is not the registered one while
    reporting the registered digest.
    """
    with pytest.raises(ValueError, match="Nyquist"):
        population.realize(detectors=["E1"], duration=4.0, sampling_frequency=1024.0, seed=1)


def test_a_model_scoped_with_a_zero_rate_states_that_a_channel_carries_nothing() -> None:
    """The coverage rule's own escape hatch, exercised through a population.

    An interferometer no model claims is refused; an interferometer claimed by a model with
    rate zero is the supported way to say it carries no glitches, and the decomposition has
    to report that as a zero rather than omit the row.
    """
    quiet = BlipGlitch(
        rate=0.0,
        amplitude_distribution=LogNormalAmplitudeDistribution(mean=1.0, std=0.0),
        detectors=["E3"],
    )
    base = et_o3_anchored_population()
    scoped = replace(
        base,
        classes=(
            *(replace(entry, model=replace_detectors(entry.model, ["E1", "E2"])) for entry in base.classes),
            GlitchClass(
                name="quiet_channel",
                morphology="none",
                description="States that E3 carries no glitches.",
                model=quiet,
            ),
        ),
    )
    rows = scoped.expected_counts(livetime_seconds=1e5, detectors=["E1", "E2", "E3"])
    assert [(row.glitch_class, row.detector) for row in rows if row.detector == "E3"] == [("quiet_channel", "E3")]
    assert all(row.expected == 0.0 for row in rows if row.detector == "E3")
