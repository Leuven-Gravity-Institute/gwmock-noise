def test_the_bundled_summary_is_internally_consistent(summary: dict) -> None:
    """Each class's rate is its count over the livetime it was counted in.

    The summary is generated, so this is not testing arithmetic -- it is testing that the
    file in the tree was generated by the harness in the tree, against the selection the
    harness declares. A summary hand-edited to move a rate fails here.
    """
    assert summary["selection"] == {"snr_minimum": SNR_MINIMUM, "confidence_minimum": CONFIDENCE_MINIMUM}
    livetime = summary["livetime_seconds"]
    assert livetime["pooled"] == pytest.approx(livetime["H1"] + livetime["L1"])
    for block in summary["classes"].values():
        for key in ("H1", "L1", "pooled"):
            assert block["rate_hz"][key] == pytest.approx(block["counts"][key] / livetime[key], rel=1e-12)
        assert block["counts"]["pooled"] == block["counts"]["H1"] + block["counts"]["L1"]


