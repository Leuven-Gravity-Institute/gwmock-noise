def test_the_hill_estimator_recovers_an_index_it_is_given() -> None:
    """The estimator the anchors rest on, checked against a distribution of known index.

    An anchor is only as good as the estimator that produced it, and ``hill_index`` is
    used by nothing else in the tree, so nothing else would catch it being wrong by a
    factor of the log base or by one.
    """
    rng = np.random.default_rng(20260919)
    truth = 1.4
    sample = 7.5 * (1.0 - rng.random(200_000)) ** (-1.0 / truth)
    estimate, stderr, count = hill_index(sample, 7.5)
    assert count == sample.size
    assert estimate == pytest.approx(truth, abs=5.0 * stderr)


