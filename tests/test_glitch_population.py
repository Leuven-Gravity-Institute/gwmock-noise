def test_the_expected_count_is_the_product_of_the_factors_it_reports(population: GlitchPopulation) -> None:
    """The decomposition is not a commentary on the total; it is the total."""
    rows = population.expected_counts(livetime_seconds=2048.0, detectors=["E1", "E2", "E3"], snr_threshold=10.0)
    assert len(rows) == 6
    for row in rows:
        assert row.expected == pytest.approx(
            row.rate_hz * row.livetime_seconds * row.participation * row.selection, rel=1e-12
        )
        assert row.network_events == pytest.approx(row.expected / row.participation, rel=1e-12)


def test_the_selection_factor_is_the_survival_of_the_registered_amplitude_law(
    population: GlitchPopulation,
) -> None:
    """Read off the distribution in closed form, not estimated from a realization."""
    rows = population.expected_counts(livetime_seconds=1.0, detectors=["E1"], snr_threshold=20.0)
    for row in rows:
        model = population.model_for(row.glitch_class)
        assert row.selection == pytest.approx(snr_survival(model.snr, 20.0))
    assert all(0.0 < row.selection < 1.0 for row in rows)

    unfiltered = population.expected_counts(livetime_seconds=1.0, detectors=["E1"])
    assert all(row.selection == 1.0 for row in unfiltered)


def test_participation_enters_the_per_channel_count_but_not_the_network_count() -> None:
    """Halving the participation halves what a channel sees and leaves the network alone."""
    full = et_o3_anchored_population()
    half = et_o3_anchored_population(participation_probability=0.5)

    def coherent_row(candidate: GlitchPopulation) -> object:
        return next(
            row
            for row in candidate.expected_counts(livetime_seconds=3600.0, detectors=["E1", "E2"])
            if row.glitch_class == "network_coherent" and row.detector == "E1"
        )

    one, other = coherent_row(full), coherent_row(half)
    assert other.expected == pytest.approx(0.5 * one.expected)
    assert other.network_events == pytest.approx(one.network_events)


def test_the_registered_counts_are_what_a_realization_produces() -> None:
    """The decomposition against the generator, which is the check that matters.

    A rate that is per-channel where the code treats it as per-network, or a participation
    factor applied twice, changes the total by a factor nothing else in the suite would
    notice. The population here is the registered one with its two rates raised, so a few
    hundred seconds of data carries enough events for a Poisson comparison to bite.
    """
    detectors = ["E1", "E2", "E3"]
    livetime = 400.0
    busy = _busy_population()
    realization = busy.realize(detectors=detectors, duration=livetime, sampling_frequency=SAMPLING_FREQUENCY, seed=11)

    expectation = {
        (row.glitch_class, row.detector): row.expected
        for row in busy.expected_counts(livetime_seconds=livetime, detectors=detectors)
    }
    kinds = {"short_single_channel": "blip", "network_coherent": "scattered_light"}
    for (glitch_class, detector), expected in expectation.items():
        observed = sum(
            1 for event in realization.events if event["detector"] == detector and event["kind"] == kinds[glitch_class]
        )
        assert abs(observed - expected) < 4.0 * np.sqrt(expected), (
            f"{glitch_class} in {detector}: expected {expected:.1f}, observed {observed}"
        )


