"""Tests for registered glitch populations and the ``et-o3-anchored-v1`` preset.

Three separable things are pinned here.

**The anchors.** Every registered rate, tail index, truncation and frequency edge is a
measurement over two published data products, summarized in
``src/gwmock_noise/data/glitch_population/o3_reference_summary.json`` and regenerated by
``scripts/measure_glitch_population_anchors.py``. The tests assert the constants against
that summary through the same functions the harness measures with, so a constant edited by
hand -- or a summary regenerated against a different selection -- fails here rather than
quietly changing what a campaign injects.

**The pinning machinery.** A population serializes, round-trips, and digests; the digest
moves when anything registered moves, and does not move otherwise. A campaign that pins a
digest is relying on both halves of that.

**The pairing.** Arms of a paired comparison have to inject the identical glitch
realization. The realization is therefore asserted to be independent of the base noise, of
the interferometer list, and of whether it was generated in one call or streamed.
"""

