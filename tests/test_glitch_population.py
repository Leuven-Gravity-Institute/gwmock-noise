def test_the_realization_is_reproducible_for_a_fixed_seed() -> None:
    """Two calls, two populations resolved separately, one array."""
    first = _busy_population().realize(
        detectors=["E1", "E2"], duration=64.0, sampling_frequency=SAMPLING_FREQUENCY, seed=2026
    )
    second = _busy_population().realize(
        detectors=["E1", "E2"], duration=64.0, sampling_frequency=SAMPLING_FREQUENCY, seed=2026
    )

    assert first.events, "the fixture must fire events for this to say anything."
    for detector in ("E1", "E2"):
        assert np.array_equal(first.strain[detector], second.strain[detector])
    assert first.events == second.events
    assert first.stamp == second.stamp


def test_a_different_seed_gives_a_different_realization() -> None:
    """The contrast case, so the reproducibility test is not passing on a constant."""
    busy = _busy_population()
    one = busy.realize(detectors=["E1"], duration=64.0, sampling_frequency=SAMPLING_FREQUENCY, seed=1)
    other = busy.realize(detectors=["E1"], duration=64.0, sampling_frequency=SAMPLING_FREQUENCY, seed=2)
    assert not np.array_equal(one.strain["E1"], other.strain["E1"])


def test_paired_geometry_arms_share_the_realization_of_every_common_channel() -> None:
    """The invariant a two-geometry comparison is measuring against.

    Run the same population and seed over a three-interferometer network and over a
    two-interferometer one. The channels both networks contain have to carry the identical
    glitch strain, or the difference between the geometries is partly the difference
    between two random draws.
    """
    busy = _busy_population()
    triangle = busy.realize(detectors=["E1", "E2", "E3"], duration=64.0, sampling_frequency=SAMPLING_FREQUENCY, seed=5)
    pair = busy.realize(detectors=["E1", "E2"], duration=64.0, sampling_frequency=SAMPLING_FREQUENCY, seed=5)

    assert triangle.events
    for detector in ("E1", "E2"):
        assert np.array_equal(triangle.strain[detector], pair.strain[detector])


def test_paired_signal_and_noise_arms_add_the_same_glitch_array() -> None:
    """What "bit-identical glitches between the arms" means in practice.

    Two arms are built over *different* base noise and given the same seed. They have to
    inject glitch for glitch the same transients, because the glitch stream is drawn from
    its own seeded generator and knows nothing about what it is being added to. Each arm's
    strain is then its own base plus the shared realization, to the precision floating-point
    summation order allows -- and a campaign that ingests one strain file into both arms
    removes even that residual, which is why the realization is exposed as an array.
    """
    busy = _busy_population()
    detectors = ["E1", "E2"]
    duration, seed = 32.0, 808
    realization = busy.realize(detectors=detectors, duration=duration, sampling_frequency=SAMPLING_FREQUENCY, seed=seed)
    assert realization.events, "the fixture must fire events for this to say anything."

    def base_for(psd_file: str) -> ColoredNoiseSimulator:
        # Colored against an Einstein Telescope curve so the noise and the glitches are the
        # same order of magnitude. Adding a 1e-24 strain to unit-amplitude white noise would
        # round it away, and the comparison would pass for a reason unrelated to glitches.
        return ColoredNoiseSimulator(
            psd_file=psd_file,
            duration=duration,
            sampling_frequency=SAMPLING_FREQUENCY,
            detectors=detectors,
            seed=seed,
            low_frequency_cutoff=5.0,
        )

    catalogues = []
    for psd_file in ("ET_10_full_cryo_psd", "ET_15_full_cryo_psd"):
        injector = busy.build_injector(base_for(psd_file))
        arm = injector.generate(duration, SAMPLING_FREQUENCY, detectors, seed=seed)
        catalogues.append(injector.glitch_events)
        without = base_for(psd_file).generate(duration, SAMPLING_FREQUENCY, detectors, seed=seed)
        for detector in detectors:
            scale = float(np.sqrt(np.mean(np.square(arm[detector]))))
            assert scale > 0.0
            assert np.allclose(
                arm[detector],
                without[detector] + realization.strain[detector],
                rtol=0.0,
                atol=1e-12 * scale,
            )
            assert not np.array_equal(arm[detector], without[detector]), (
                "the fixture must inject glitches the base noise does not swamp."
            )

    assert catalogues[0] == catalogues[1] == realization.events


def test_the_realization_streams_to_the_same_samples_as_one_call() -> None:
    """A campaign writing segment files must get what a single call would have produced."""
    busy = _busy_population()
    detectors = ["E1", "E2"]
    whole = busy.realize(detectors=detectors, duration=64.0, sampling_frequency=SAMPLING_FREQUENCY, seed=31)

    from gwmock_noise.simulators.glitches import _ZeroNoiseSimulator

    injector = busy.build_injector(
        _ZeroNoiseSimulator(detectors=detectors, duration=16.0, sampling_frequency=SAMPLING_FREQUENCY, seed=31)
    )
    chunks: dict[str, list[np.ndarray]] = {detector: [] for detector in detectors}
    seed: int | None = 31
    for _ in range(4):
        result = injector.generate(16.0, SAMPLING_FREQUENCY, detectors, seed=seed)
        for detector in detectors:
            chunks[detector].append(result[detector])
        seed = None

    assert whole.events
    for detector in detectors:
        assert np.array_equal(np.concatenate(chunks[detector]), whole.strain[detector])


