"""ARMA / state-space noise simulator fitted from a tabulated PSD.

The simulator combines three pieces so that a tabulated detector spectrum with
lines can be generated by a bounded-state IIR filter:

* **Pole placement.** Every requested (or detected) spectral line contributes a
  conjugate pole pair at the line frequency, with a radius set by the line
  width. Those poles anchor the sharp features an all-pole fit of the same
  order cannot hold.
* **Levinson-Durbin denominator.** The target is pre-whitened by the placed
  poles and the remaining smooth part is fitted with the stable Levinson
  recursion, so the denominator is stable by construction.
* **Log-spectrum-matched numerator.** The numerator is the truncated
  minimum-phase spectral factor of the pre-whitened target, which is the
  log-spectrum matching step.

The fit exposes both orders, the state size, the conditioning diagnostics and
the relative PSD residual per band. A fit that cannot produce a finite, stable
filter raises instead of degrading.

What pole placement costs. A placed pole's peak height is fixed by its radius,
which the line width sets, and not by how far the target's line actually rises
above its surroundings. On the bundled presets, whose tabulated lines are one
to three samples wide, that makes the model spectrum overshoot at the line:
placing the single strongest line of the measured O3 Hanford curve raises the
worst band residual from 0.36 to 0.81, and placing the eight the detector
selects raises it to about 1e14, unchanged when the moving-average order is
raised from 32 to 1024. Pole placement is therefore useful for lines whose
width is known and whose contrast is modest, and the default is to place none.
``docs/dev/anchored_quantities.md`` records the measurement.
"""

